import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalizeJson } from '../packages/shared/src/portable-update.ts';

const here = dirname(fileURLToPath(import.meta.url));
const testdata = join(here, '..', 'launcher', 'testdata');
const version = '0.0.26';

const files = [
  { path: '\u8363\u76c8\u9b54\u65b9.exe', content: 'portable program binary fixture' },
  { path: 'resources/app.asar', content: 'asar fixture content' },
  { path: 'resources/runtime/node.exe', content: 'runtime fixture binary' },
];

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

const fileManifest = {
  schemaVersion: 1,
  version,
  files: files.map((file) => ({
    path: file.path,
    size: Buffer.byteLength(file.content),
    sha256: sha256(file.content),
  })),
};

const { publicKey, privateKey } = generateKeyPairSync('ed25519');
const payload = {
  schemaVersion: 1,
  channel: 'internal',
  version,
  minLauncherVersion: '1.0.0',
  packageUrl: `https://api.rongyinghudong.com/updates/internal/${version}/portable.zip`,
  packageSize: 4096,
  packageSha256: sha256('portable package fixture'),
  fileManifestSha256: sha256(canonicalizeJson(fileManifest)),
  publishedAt: '2026-09-21T00:00:00.000Z',
  mandatory: false,
};
const signature = sign(null, Buffer.from(canonicalizeJson(payload), 'utf8'), privateKey).toString('base64');

await rm(testdata, { recursive: true, force: true });
for (const file of files) {
  const target = join(testdata, 'program', ...file.path.split('/'));
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, file.content, 'utf8');
}
await writeFile(join(testdata, 'manifest.json'), `${JSON.stringify({ ...payload, signature }, null, 2)}\n`, 'utf8');
await writeFile(join(testdata, 'portable-files.json'), `${JSON.stringify(fileManifest, null, 2)}\n`, 'utf8');
await writeFile(
  join(testdata, 'public-key.der.b64'),
  `${publicKey.export({ type: 'spki', format: 'der' }).toString('base64')}\n`,
  'utf8',
);
await writeFile(
  join(testdata, 'README.md'),
  [
    '# Portable launcher fixtures',
    '',
    'Generated by `node scripts/make-portable-launcher-fixtures.mjs`.',
    '',
    'The Ed25519 key pair is ephemeral: every regeneration rewrites the',
    'public key and the signed manifest together, so the pair always',
    'matches. No private key is ever written to disk or committed.',
    '',
    'The Go launcher tests read `manifest.json`, `portable-files.json` and',
    '`public-key.der.b64` from this directory, and copy `program/` into a',
    'temporary directory before mutating it.',
    '',
  ].join('\n'),
  'utf8',
);
console.log(`portable launcher fixtures written to ${testdata}`);
