/**
 * 素材（附件/材料）扩展名的**单一真源**。
 *
 * ⚠️ 为什么必须只有一份：同一条用户动作（把一张图带进对话）会经过两个入口 ——
 *    拖入/选入（主进程 `file-import.ts` 的对话框过滤 + 导入白名单）与粘贴/暂存
 *    （渲染层 `attachment-actions.ts` 的「识别图片」建议行）。两份清单不一致时，
 *    用户看到的是自相矛盾的承诺："粘贴 .gif 给你「识别图片」，拖入 .gif 说类型不支持"
 *    （2026-10-07 质量战役区 2 · P3-1）。
 *
 * 清单口径：**以导入白名单为准**（png / jpg / jpeg / webp）。
 *    gif / svg / bmp 在产品里没有可兑现的图片通路（模型侧多数不认这些格式的 base64，
 *    导入侧也从未放行过），所以它们既不进导入白名单，也不该在粘贴侧被承诺「识别图片」。
 */
export const IMAGE_FILE_EXTENSIONS = ['png', 'jpg', 'jpeg', 'webp'] as const;
